# ================================================================
# KLASIFIKASI
# ================================================================
def classify_aircraft(aircraft_type):
    """Tentukan kategori ikon berdasarkan string aircraftType."""
    t = (aircraft_type or "").lower().replace("-", "").replace(" ", "")

    # ==== Khusus ====
    if "concorde" in t or t.startswith("conc"):
        return "concorde"
    if t.startswith("md") and any(c.isdigit() for c in t):
        return "md_series"
    if any(k in t for k in ["heli", "rotor", "bell", "uh", "ah1", "ec1",
                            "aw1", "r22", "r44", "r66"]):
        return "helicopter"
    if any(k in t for k in ["glider", "sailplane", "ask", "discus", "asw"]):
        return "glider"
    if "balloon" in t or "airship" in t or "blimp" in t:
        return "balloon"

    # ==== Airbus ====
    if any(k in t for k in ["a380", "a388", "a340", "a345", "a346"]):
        return "heavy_4engine"
    if any(k in t for k in ["a350", "a359", "a35k", "a330", "a332", "a333",
                            "a300", "a310"]):
        return "wide_body"
    if any(k in t for k in ["a320", "a321", "a319", "a318", "a220"]):
        return "narrow_body"

    # ==== Boeing ====
    if any(k in t for k in ["747", "b741", "b742", "b743", "b744", "b748"]):
        return "heavy_4engine"
    if any(k in t for k in ["777", "b772", "b773", "b77w", "787", "b788",
                            "b789", "b78x", "767", "b762", "b763"]):
        return "wide_body"
    if any(k in t for k in ["737", "b731", "b732", "b733", "b734", "b735",
                            "b736", "b737", "b738", "b739", "b717"]):
        return "narrow_body"

    # ==== Embraer ====
    if any(k in t for k in ["e170", "e175", "e190", "e195", "e290", "e295"]):
        return "narrow_body"

    # ==== Bombardier CRJ ====
    if any(k in t for k in ["crj", "cr9", "cr7"]):
        return "narrow_body"

    # ==== Business jets ====
    if any(k in t for k in ["citation", "gulfstream", "learjet", "phenom",
                            "legacy", "falcon", "global", "challenger",
                            "g550", "g650", "g700", "bizjet"]):
        return "light_jet"

    # ==== Light aircraft ====
    if any(k in t for k in ["cessna", "caravan", "c172", "c182", "c206",
                            "c208", "172", "182", "206", "208", "piper",
                            "pa28", "sr22"]):
        return "cessna"

    # ==== Turboprop ====
    if any(k in t for k in ["atr", "q400", "dash8", "kingair", "twinotter",
                            "saab340", "saab2000", "dornier328"]):
        return "twin_prop"

    return "narrow_body"
